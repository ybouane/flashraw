//! Compiles camera-db/cameras/*.toml into static lookup tables.
use std::fmt::Write as _;
use std::path::PathBuf;

include!("src/schema.rs");

fn norm(s: &str) -> String {
    s.split_whitespace().collect::<Vec<_>>().join(" ").to_uppercase()
}

fn main() {
    let manifest = PathBuf::from(std::env::var("CARGO_MANIFEST_DIR").unwrap());
    let mut dir = manifest.join("../../camera-db/cameras");
    if !dir.exists() {
        dir = manifest.join("data/cameras");
    }
    println!("cargo:rerun-if-changed={}", dir.display());
    let mut cams: Vec<DbCamera> = Vec::new();
    let mut mats: Vec<DbMatrix> = Vec::new();
    let mut files: Vec<_> = std::fs::read_dir(&dir)
        .map(|r| {
            r.filter_map(|e| e.ok()).map(|e| e.path()).filter(|p| p.extension().is_some_and(|x| x == "toml")).collect()
        })
        .unwrap_or_default();
    files.sort();
    for f in &files {
        println!("cargo:rerun-if-changed={}", f.display());
        let text = std::fs::read_to_string(f).unwrap();
        let db: DbFile = toml::from_str(&text).unwrap_or_else(|e| panic!("{}: {e}", f.display()));
        cams.extend(db.cameras);
        mats.extend(db.matrices);
    }
    let mut out = String::new();
    out.push_str("// @generated by build.rs from camera-db/cameras/*.toml — do not edit.\n");
    let q = |s: &str| format!("{s:?}");
    writeln!(out, "pub static CAMERAS: &[Camera] = &[").unwrap();
    for c in &cams {
        let aliases: Vec<String> =
            c.aliases.iter().map(|a| format!("({}, {})", q(&a.model), q(&a.canonical))).collect();
        let sensors: Vec<String> = c
            .sensor
            .iter()
            .map(|s| {
                format!(
                    "SensorInfo {{ black: {}, white: {}, black_colors: &{:?}, iso_min: {}, iso_max: {}, iso_list: &{:?} }}",
                    s.black,
                    s.white,
                    s.black_colors,
                    s.iso_min.unwrap_or(0),
                    s.iso_max.unwrap_or(0),
                    s.iso_list
                )
            })
            .collect();
        let hints: Vec<String> = c.hints.iter().map(|(k, v)| format!("({}, {})", q(k), q(v))).collect();
        writeln!(
            out,
            "  Camera {{ make: {}, model: {}, mode: {}, canonical_make: {}, canonical_model: {}, aliases: &[{}], cfa: {}, crop: {}, black_areas_v: &{:?}, black_areas_h: &{:?}, sensors: &[{}], color_matrix: &{:?}, hints: &[{}], no_size_match: {} }},",
            q(&c.make), q(&c.model), q(&c.mode), q(&c.canonical_make), q(&c.canonical_model),
            aliases.join(", "),
            c.cfa.as_ref().map(|s| format!("Some({})", q(s))).unwrap_or("None".into()),
            c.crop.map(|v| format!("Some({v:?})")).unwrap_or("None".into()),
            c.black_areas_v, c.black_areas_h,
            sensors.join(", "),
            c.color_matrix,
            hints.join(", "),
            c.no_size_match,
        )
        .unwrap();
    }
    writeln!(out, "];").unwrap();
    // Sorted index: (normalised "MAKE\0MODEL\0MODE", camera index), including aliases.
    let mut index: Vec<(String, usize)> = Vec::new();
    for (i, c) in cams.iter().enumerate() {
        index.push((format!("{}\t{}\t{}", norm(&c.make), norm(&c.model), norm(&c.mode)), i));
        for a in &c.aliases {
            index.push((format!("{}\t{}\t{}", norm(&c.make), norm(&a.model), norm(&c.mode)), i));
        }
    }
    index.sort();
    index.dedup_by(|a, b| a.0 == b.0);
    writeln!(out, "pub static INDEX: &[(&str, u16)] = &[").unwrap();
    for (k, i) in &index {
        writeln!(out, "  ({}, {}),", q(k), i).unwrap();
    }
    writeln!(out, "];").unwrap();
    writeln!(out, "pub static MATRICES: &[FallbackMatrix] = &[").unwrap();
    for m in &mats {
        writeln!(
            out,
            "  FallbackMatrix {{ canonical_make: {}, model_prefix: {}, black: {}, white: {}, color_matrix: &{:?} }},",
            q(&m.canonical_make),
            q(&m.model_prefix),
            m.black,
            m.white,
            m.color_matrix
        )
        .unwrap();
    }
    writeln!(out, "];").unwrap();
    let dest = PathBuf::from(std::env::var("OUT_DIR").unwrap()).join("cameras.rs");
    std::fs::write(dest, out).unwrap();
}
