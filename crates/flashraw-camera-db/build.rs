//! Compiles camera-db/cameras.json into static lookup tables.
use std::fmt::Write as _;
use std::path::PathBuf;

include!("src/schema.rs");

fn norm(s: &str) -> String {
    s.split_whitespace().collect::<Vec<_>>().join(" ").to_uppercase()
}

fn main() {
    let manifest = PathBuf::from(std::env::var("CARGO_MANIFEST_DIR").unwrap());
    let mut path = manifest.join("../../camera-db/cameras.json");
    if !path.exists() {
        path = manifest.join("data/cameras.json");
    }
    println!("cargo:rerun-if-changed={}", path.display());
    let text = std::fs::read_to_string(&path).unwrap_or_else(|e| panic!("{}: {e}", path.display()));
    let db: DbFile = serde_json::from_str(&text).unwrap_or_else(|e| panic!("{}: {e}", path.display()));
    let cams = db.cameras;
    let mats = db.matrices;
    let mut out = String::new();
    out.push_str("// @generated by build.rs from camera-db/cameras.json — do not edit.\n");
    let q = |s: &str| format!("{s:?}");
    writeln!(out, "pub static CAMERAS: &[Camera] = &[").unwrap();
    for c in &cams {
        let aliases: Vec<String> =
            c.aliases.iter().map(|a| format!("({}, {})", q(&a.model), q(&a.canonical))).collect();
        let sensors: Vec<String> = c
            .sensor
            .iter()
            .map(|s| {
                format!(
                    "SensorInfo {{ black: {}, white: {}, black_colors: &{:?}, iso_min: {}, iso_max: {}, iso_list: &{:?} }}",
                    s.black,
                    s.white,
                    s.black_colors,
                    s.iso_min.unwrap_or(0),
                    s.iso_max.unwrap_or(0),
                    s.iso_list
                )
            })
            .collect();
        let hints: Vec<String> = c.hints.iter().map(|(k, v)| format!("({}, {})", q(k), q(v))).collect();
        let orientation = c
            .orientation
            .as_ref()
            .map(|o| {
                format!(
                    "Some(CameraOrientation {{ policy: {}, maker_note_offset: {:?}, auto_rotate_offset: {:?} }})",
                    q(&o.policy),
                    o.maker_note_offset,
                    o.auto_rotate_offset
                )
            })
            .unwrap_or("None".into());
        writeln!(
            out,
            "  Camera {{ make: {}, model: {}, mode: {}, canonical_make: {}, canonical_model: {}, aliases: &[{}], cfa: {}, crop: {}, black_areas_v: &{:?}, black_areas_h: &{:?}, sensors: &[{}], color_matrix: &{:?}, hints: &[{}], no_size_match: {}, orientation: {} }},",
            q(&c.make), q(&c.model), q(&c.mode), q(&c.canonical_make), q(&c.canonical_model),
            aliases.join(", "),
            c.cfa.as_ref().map(|s| format!("Some({})", q(s))).unwrap_or("None".into()),
            c.crop.map(|v| format!("Some({v:?})")).unwrap_or("None".into()),
            c.black_areas_v, c.black_areas_h,
            sensors.join(", "),
            c.color_matrix,
            hints.join(", "),
            c.no_size_match,
            orientation,
        )
        .unwrap();
    }
    writeln!(out, "];").unwrap();
    // Sorted index: (normalised "MAKE\0MODEL\0MODE", camera index), including aliases.
    let mut index: Vec<(String, usize)> = Vec::new();
    for (i, c) in cams.iter().enumerate() {
        index.push((format!("{}\t{}\t{}", norm(&c.make), norm(&c.model), norm(&c.mode)), i));
        for a in &c.aliases {
            index.push((format!("{}\t{}\t{}", norm(&c.make), norm(&a.model), norm(&c.mode)), i));
        }
    }
    index.sort();
    index.dedup_by(|a, b| a.0 == b.0);
    writeln!(out, "pub static INDEX: &[(&str, u16)] = &[").unwrap();
    for (k, i) in &index {
        writeln!(out, "  ({}, {}),", q(k), i).unwrap();
    }
    writeln!(out, "];").unwrap();
    writeln!(out, "pub static MATRICES: &[FallbackMatrix] = &[").unwrap();
    for m in &mats {
        writeln!(
            out,
            "  FallbackMatrix {{ canonical_make: {}, model_prefix: {}, black: {}, white: {}, color_matrix: &{:?} }},",
            q(&m.canonical_make),
            q(&m.model_prefix),
            m.black,
            m.white,
            m.color_matrix
        )
        .unwrap();
    }
    writeln!(out, "];").unwrap();
    writeln!(out, "pub static ALIAS_GROUPS: &[AliasGroup] = &[").unwrap();
    for g in &db.model_aliases {
        let al: Vec<String> = g.aliases.iter().map(|a| q(a)).collect();
        writeln!(
            out,
            "  AliasGroup {{ canonical_make: {}, model: {}, aliases: &[{}] }},",
            q(&g.canonical_make),
            q(&g.model),
            al.join(", ")
        )
        .unwrap();
    }
    writeln!(out, "];").unwrap();
    writeln!(out, "pub static SIZE_RULES: &[SizeRule] = &[").unwrap();
    for r in &db.size_rules {
        writeln!(
            out,
            "  SizeRule {{ canonical_make: {}, raw_width: {}, raw_height: {}, left: {}, top: {}, width_delta: {}, height_delta: {} }},",
            q(&r.canonical_make), r.raw_width, r.raw_height, r.left, r.top, r.width_delta, r.height_delta
        )
        .unwrap();
    }
    writeln!(out, "];").unwrap();
    writeln!(out, "pub static ORIENTATION_RULES: &[OrientationRule] = &[").unwrap();
    for r in &db.orientation_rules {
        writeln!(
            out,
            "  OrientationRule {{ canonical_make: {}, model_prefix: {}, policy: {} }},",
            q(&r.canonical_make),
            q(&r.model_prefix),
            q(&r.policy)
        )
        .unwrap();
    }
    writeln!(out, "];").unwrap();
    let dest = PathBuf::from(std::env::var("OUT_DIR").unwrap()).join("cameras.rs");
    std::fs::write(dest, out).unwrap();
}
