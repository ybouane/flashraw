/// Keystream parameters derived from the serial number and shutter count.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct Key {
    ci: u8,
    cj0: u8,
}

impl Key {
    /// `serial_index`: the low byte of the numeric serial (or the model-specific
    /// substitute for non-numeric serials); `count`: the 4 raw bytes of tag 0xA7.
    pub fn new(serial_index: u8, count: [u8; 4]) -> Key {
        let key = count[0] ^ count[1] ^ count[2] ^ count[3];
        Key { ci: XLAT[0][serial_index as usize], cj0: XLAT[1][key as usize] }
    }

    /// XOR-decrypt `buf` in place (the keystream restarts for every block).
    pub fn decrypt(&self, buf: &mut [u8]) {
        let mut cj = self.cj0;
        let mut ck: u8 = 0x60;
        for b in buf.iter_mut() {
            cj = cj.wrapping_add(self.ci.wrapping_mul(ck));
            ck = ck.wrapping_add(1);
            *b ^= cj;
        }
    }
}

/// The serial-derived key index from tag 0x1D (an ASCII serial). Numeric serials use
/// their low byte; the first non-digit switches to a fixed substitute (34 on the D50,
/// 96 elsewhere), mirroring the camera firmware.
pub fn serial_index(serial: &[u8], model: &str) -> u8 {
    let mut n: u32 = 0;
    for &c in serial {
        if c == 0 {
            break;
        }
        if !c.is_ascii_digit() {
            let m = model.trim();
            let is_d50 = m == "D50"
                || (m.len() >= 4 && m.ends_with("D50") && !m.as_bytes()[m.len() - 4].is_ascii_alphanumeric());
            return if is_d50 { 34 } else { 96 };
        }
        n = n.wrapping_mul(10).wrapping_add((c - b'0') as u32);
    }
    (n & 0xFF) as u8
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn decrypt_is_an_involution() {
        let k = Key::new(0x42, [1, 2, 3, 4]);
        let orig: Vec<u8> = (0..324).map(|i| (i * 7) as u8).collect();
        let mut b = orig.clone();
        k.decrypt(&mut b);
        assert_ne!(b, orig);
        k.decrypt(&mut b);
        assert_eq!(b, orig);
    }

    #[test]
    fn serials() {
        assert_eq!(serial_index(b"3001234\0", "D300"), (3001234u32 & 0xFF) as u8);
        assert_eq!(serial_index(b"12A", "D50"), 34);
        assert_eq!(serial_index(b"NIKON D50 12A", "NIKON D50"), 34);
        assert_eq!(serial_index(b"X", "D70"), 96);
    }
}
