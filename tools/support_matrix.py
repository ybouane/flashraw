#!/usr/bin/env python3
"""Assemble docs/support-matrix.tsv (used by `flashraw supported`) and the support table
in docs/formats.md from the per-vendor docs/support/*.tsv files.

usage: tools/support_matrix.py [--check]   (--check fails if the outputs are stale)
"""
import glob, os, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
rows = []
for p in sorted(glob.glob(os.path.join(ROOT, "docs/support/*.tsv"))):
    for line in open(p, encoding="utf-8"):
        line = line.rstrip("\n")
        if not line.strip() or line.startswith("#"):
            continue
        c = line.split("\t")
        if c[0].upper() == "FORMAT":
            continue
        c += [""] * (5 - len(c))
        rows.append(c[:5])
rows.sort(key=lambda c: (c[0], c[1]))

matrix = "# format\tmode\tcompression\tstatus\tnotes\n# GENERATED by tools/support_matrix.py from docs/support/*.tsv — do not edit.\n"
matrix += "".join("\t".join(c) + "\n" for c in rows)

counts = {}
for c in rows:
    counts[c[3]] = counts.get(c[3], 0) + 1
table = "<!-- BEGIN GENERATED SUPPORT TABLE (tools/support_matrix.py) -->\n"
table += "Status counts: " + ", ".join(f"{k}: {v}" for k, v in sorted(counts.items())) + "\n\n"
table += "| Format | Mode | Compression | Status | Notes |\n|---|---|---|---|---|\n"
for c in rows:
    table += "| " + " | ".join(x.replace("|", "/") for x in c) + " |\n"
table += "<!-- END GENERATED SUPPORT TABLE -->\n"

fmt_path = os.path.join(ROOT, "docs/formats.md")
fmt = open(fmt_path, encoding="utf-8").read()
a = fmt.index("<!-- BEGIN GENERATED SUPPORT TABLE")
b = fmt.index("<!-- END GENERATED SUPPORT TABLE -->") + len("<!-- END GENERATED SUPPORT TABLE -->\n")
new_fmt = fmt[:a] + table + fmt[b:]
mpath = os.path.join(ROOT, "docs/support-matrix.tsv")
if "--check" in sys.argv:
    stale = open(mpath, encoding="utf-8").read() != matrix or fmt != new_fmt
    if stale:
        print("support matrix is stale: run tools/support_matrix.py")
        sys.exit(1)
    print(f"{len(rows)} rows up to date")
else:
    open(mpath, "w", encoding="utf-8").write(matrix)
    open(fmt_path, "w", encoding="utf-8").write(new_fmt)
    print(f"wrote {len(rows)} rows")
